static uint8_t glyph_row(char c,int r){
    if(c>='a'&&c<='z')c-=32;
    if(c>='A'&&c<='Z')return glyph_letters[c-'A'][r];
    if(c>='0'&&c<='9')return glyph_digits[c-'0'][r];
    switch(c){
    case '.':return r==6?4:0;case ':':return r==2||r==5?4:0;
    case '-':return r==3?14:0;case '_':return r==6?31:0;
    case '/':return (uint8_t)(1U<<(r*4/6));case '\\':return (uint8_t)(16U>>(r*4/6));
    case '+':return r==3?31:(r>=1&&r<=5?4:0);case '=':return r==2||r==4?31:0;
    case '[':return r==0||r==6?14:8;case ']':return r==0||r==6?14:2;
    case ';':return r==2||r==5?4:r==6?8:0;case '\'':return r<2?4:0;
    case ',':return r==5?4:r==6?8:0;case '`':return r==0?8:r==1?4:0;
    case '!':return r<4||r==6?4:0;case '?':{const uint8_t g[]={14,17,1,2,4,0,4};return g[r];}
    case '<':return r==3?8:(r==2||r==4)?4:(r==1||r==5)?2:0;
    case '>':return r==3?2:(r==2||r==4)?4:(r==1||r==5)?8:0;
    case '(':return r==0||r==6?2:r==1||r==5?4:8;
    case ')':return r==0||r==6?8:r==1||r==5?4:2;
    case '*':return r==2||r==4?21:r==3?14:0;
    case '#':return r==2||r==4?31:10;
    default:return 0;
    }
}
